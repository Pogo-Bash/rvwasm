#!/usr/bin/env python3
"""Write closure-noffi.h for libwayland without libffi (Wasm has no way to call a
function with a signature chosen at run time; libffi has no wasm64 port).

wl_closure_invoke calls a listener as fn(data, target, args...), where every
argument is either 32-bit (int, uint, fixed, fd; and new_id on the server's
side) or a pointer (string, object, array; new_id on the client's side). On
wasm64 that makes a signature a string of i32/i64; here is a call for every
such string of up to MAX arguments, selected by (1 << count) | bits, bit k set
when argument k is a pointer."""
import sys
MAX = int(sys.argv[1]) if len(sys.argv) > 1 else 10
out = ["/* Generated by native/wayland-noffi.py; do not edit. */",
       "static void",
       "wl_noffi_call(void (*fn)(void), void *data, void *target, unsigned key, const uint64_t *a)",
       "{",
       "\tswitch (key) {"]
for n in range(MAX + 1):
    for bits in range(1 << n):
        types = ["void *" if bits >> k & 1 else "uint32_t" for k in range(n)]
        casts = ["(void *)(uintptr_t)a[%d]" % k if bits >> k & 1 else "(uint32_t)a[%d]" % k for k in range(n)]
        out.append("\tcase %d: ((void (*)(void *, void *%s))fn)(data, target%s); return;" % (
            (1 << n) | bits, "".join(", " + t for t in types), "".join(", " + c for c in casts)))
out += ["\tdefault: wl_abort(\"wl_noffi_call: listener with too many arguments\\n\");", "\t}", "}", "#define WL_NOFFI_MAX %d" % MAX]
print("\n".join(out))
