#!/usr/bin/env python3
# Writes rv/virtgpu_formats.h: for every virgl format (Mesa's src/virtio/virtio-gpu/virgl_hw.h, enum
# virgl_formats), the bytes of one block and the block's width and height, which rv's emulated
# virtio-gpu (rv/virtgpu.c) needs to say how many bytes a transfer moves.
#   gen-virgl-formats.py virgl_hw.h > rv/virtgpu_formats.h
# Formats it cannot size (planar YUV and the like) get 0: rv then lets a transfer take the rest of the
# resource's backing, which is always enough.
import re
import sys

src = open(sys.argv[1]).read()
body = src[src.index("enum virgl_formats"):]
body = body[:body.index("};")]
formats = [(m.group(1), int(m.group(2))) for m in re.finditer(r"VIRGL_FORMAT_([A-Z0-9_]+)\s*=\s*(\d+)", body)]

# Compressed and packed formats: (bytes, block width, block height).
SPECIAL = {
    "NONE": (0, 1, 1),
    "R1_UNORM": (1, 8, 1),
    "Z24_UNORM_S8_UINT_AS_R8G8B8A8": (4, 1, 1),
    "R9G9B9E5_FLOAT": (4, 1, 1),
    "R11G11B10_FLOAT": (4, 1, 1),
}
for name in ("UYVY", "YUYV", "YVYU", "VYUY", "R8G8_B8G8_UNORM", "G8R8_G8B8_UNORM", "R8G8_R8B8_UNORM",
             "G8R8_B8R8_UNORM", "B8G8_R8G8_UNORM", "G8B8_G8R8_UNORM", "R8B8_R8G8_UNORM", "B8R8_G8R8_UNORM"):
    SPECIAL[name] = (4, 2, 1)


def compressed(name):
    if name.startswith(("DXT1_", "RGTC1_", "LATC1_", "ETC1_")) or name in (
            "ETC2_RGB8", "ETC2_SRGB8", "ETC2_RGB8A1", "ETC2_SRGB8A1", "ETC2_R11_UNORM", "ETC2_R11_SNORM", "ATC_RGB"):
        return (8, 4, 4)
    if name.startswith(("DXT3_", "DXT5_", "RGTC2_", "LATC2_", "BPTC_", "ETC2_RG11_", "ATC_RGBA")) or name in (
            "ETC2_RGBA8", "ETC2_SRGBA8"):
        return (16, 4, 4)
    if name.startswith("FXT1_"):
        return (16, 8, 4)
    return None


def size_of(name):
    if name in SPECIAL:
        return SPECIAL[name]
    c = compressed(name)
    if c:
        return c
    # Planar and subsampled YUV: not sized here.
    if re.search(r"(^|_)(NV\d+|P0\d+|YV\d+|IYUV|AYUV|XYUV|Y2\d+|Y4\d+)($|_)", name) or "_420_" in name or \
            "_422_" in name or "_444_" in name or "_440_" in name or "_400_" in name or name.endswith(("_420_UNORM",)):
        return (0, 1, 1)
    # The channels are spelled in the name's first part(s): R8G8B8A8, Z24, S8X24, ...
    bits = 0
    for part in name.split("_"):
        for m in re.finditer(r"[RGBAXLIZSEUV](\d+)", part):
            bits += int(m.group(1))
        if part in ("UNORM", "SNORM", "FLOAT", "UINT", "SINT", "USCALED", "SSCALED", "SRGB", "FIXED", "NORM"):
            continue
    if bits == 0 or bits % 8:
        return (0, 1, 1)
    return (bits // 8, 1, 1)


print("/* Generated by gpu/tools/gen-virgl-formats.py from Mesa 25.0.7's virgl_hw.h: do not edit. */")
print("/* virgl format -> bytes per block, block width, block height (0 bytes: not known here) */")
print("static const struct { uint8_t bytes, bw, bh; } virgl_format_blocks[] = {")
for name, num in formats:
    b, w, h = size_of(name)
    print("\t[%d] = { %d, %d, %d },\t/* %s */" % (num, b, w, h, name))
print("};")
