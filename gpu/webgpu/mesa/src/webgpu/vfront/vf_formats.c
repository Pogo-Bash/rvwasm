static uint16_t to_pipe[VIRGL_FORMAT_MAX_EXTENDED];
static uint16_t to_virgl[PIPE_FORMAT_COUNT];
static bool made;

static void make(void)
{
	for (unsigned i = 0; i < ARRAY_SIZE(pairs); i++) {
		to_pipe[pairs[i].virgl] = pairs[i].pipe;
		to_virgl[pairs[i].pipe] = pairs[i].virgl;
	}
	made = true;
}

enum pipe_format vf_format(uint32_t virgl_format)
{
	if (!made)
		make();
	if (virgl_format >= VIRGL_FORMAT_MAX_EXTENDED)
		return PIPE_FORMAT_NONE;
	return (enum pipe_format)to_pipe[virgl_format];
}

uint32_t vf_virgl_format(enum pipe_format format)
{
	if (!made)
		make();
	if ((unsigned)format >= PIPE_FORMAT_COUNT)
		return 0;
	return to_virgl[format];
}
