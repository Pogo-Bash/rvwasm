#!/usr/bin/env python3
"""Write wgvk_p4.c: the P4 profile (profiles/p4-lavapipe.json: vulkaninfo --json of lavapipe under the
wgmask layer with spikes/wgmask/p4-env.sh, i.e. what zink + Blender 4.3 ran on in spike S1) as C that
fills Mesa's vk_device_extension_table, vk_features and vk_properties.

    gen-p4.py p4-lavapipe.json MESA_NATIVE_BUILD_DIR OUT.c

Only members that exist in this Mesa's generated structs are written (the build dir has
vk_physical_device_{features,properties}.h and vk_extensions.h). Identity (names, ids, UUIDs, versions)
and lavapipe-only properties are left to wgvk_physical_device.c. Run it again when the profile or the
pinned Mesa changes; the output is committed.
"""
import json, re, sys

SKIP_PROPS = {
    "apiVersion", "driverVersion", "vendorID", "deviceID", "deviceType", "deviceName", "pipelineCacheUUID",
    "deviceUUID", "driverUUID", "deviceLUID", "deviceNodeMask", "deviceLUIDValid", "driverID", "driverName",
    "driverInfo", "conformanceVersion", "shaderBinaryUUID", "shaderBinaryVersion",
    # lavapipe's own numbers that say nothing about a WebGPU device
    "minImportedHostPointerAlignment", "maxMemoryAllocationCount",
}


def members(path, struct):
    text = open(path).read()
    m = re.search(r"struct %s \{(.*?)\n\};" % struct, text, re.S)
    out = {}
    for line in m.group(1).splitlines():
        line = line.strip().rstrip(";")
        mm = re.match(r"(.+?)\s+(\w+)(\[[^\]]*\])?$", line)
        if mm and not line.startswith("/") and not line.startswith("*"):
            out[mm.group(2)] = (mm.group(1), mm.group(3))
    return out


def cval(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        return repr(v) + "f"
    if isinstance(v, int):
        return str(v) + ("ull" if v > 0x7fffffff else "")
    return None


def main():
    prof, bdir, out = sys.argv[1:4]
    d = json.load(open(prof))
    caps = d["capabilities"]["device"]
    feats = members(bdir + "/src/vulkan/runtime/vk_physical_device_features.h", "vk_features")
    props = members(bdir + "/src/vulkan/runtime/vk_physical_device_properties.h", "vk_properties")
    ext_text = open(bdir + "/src/vulkan/util/vk_extensions.h").read()
    exts_known = set(re.findall(r"bool (\w+);", ext_text.split("struct vk_device_extension_table")[1].split("};")[0]))

    L = ["/* Generated by gpu/webgpu/profiles/gen-p4.py from profiles/p4-lavapipe.json. Do not edit; regenerate.",
         " * The P4 profile of spike S1 (docs/gpu-webgpu-design.md): what wgvk must offer, natively or emulated, for",
         " * zink's GL 4.3 and Blender 4.3. Until a feature is implemented it is advertised anyway (T0 skeleton);",
         " * T1 replaces entries with what the device really does as the work lands. */",
         '#include "wgvk_private.h"', ""]
    L.append("void\nwgvk_p4_extensions(struct vk_device_extension_table *e)\n{")
    missing = []
    for name in sorted(caps["extensions"]):
        short = name[3:]
        if short in exts_known:
            L.append("   e->%s = true;" % short)
        else:
            missing.append(name)
    L.append("}\n")
    L.append("void\nwgvk_p4_features(struct vk_features *f)\n{")
    seen = set()
    for struct, fs in caps["features"].items():
        for k, v in fs.items():
            if k in feats and k not in seen and isinstance(v, bool):
                seen.add(k)
                if v:
                    L.append("   f->%s = true;" % k)
    L.append("}\n")
    L.append("void\nwgvk_p4_properties(struct vk_properties *p)\n{")
    seen = set()

    def emit(k, v):
        if k in SKIP_PROPS or k in seen or k not in props:
            return
        ctype, arr = props[k]
        if isinstance(v, list) and v and all(isinstance(x, str) and x.startswith("VK_") for x in v) and not arr:
            L.append("   p->%s = %s;" % (k, " | ".join(v)))
        elif isinstance(v, list) and not v and not arr:
            L.append("   p->%s = 0;" % k)
        elif isinstance(v, str) and v.startswith("VK_") and not arr:
            L.append("   p->%s = %s;" % (k, v))
        elif isinstance(v, list):
            if not arr or not all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in v):
                return
            for i, x in enumerate(v):
                L.append("   p->%s[%d] = %s;" % (k, i, cval(x)))
        elif isinstance(v, (bool, int, float)) and not arr:
            if "Flags" in ctype or ctype.startswith("Vk") and not ctype.startswith("VkDeviceSize") and not ctype.startswith("VkBool32"):
                L.append("   p->%s = (%s)%s;" % (k, ctype, cval(v)))
            else:
                L.append("   p->%s = %s;" % (k, cval(v)))
        else:
            return
        seen.add(k)

    for struct, ps in caps["properties"].items():
        for k, v in ps.items():
            if isinstance(v, dict):
                for k2, v2 in v.items():
                    emit(k2, v2)
            else:
                emit(k, v)
    L.append("}")
    open(out, "w").write("\n".join(L) + "\n")
    print("gen-p4: %d extensions (%d unknown to this Mesa: %s), features and properties written to %s"
          % (len(caps["extensions"]), len(missing), " ".join(missing), out))


main()
