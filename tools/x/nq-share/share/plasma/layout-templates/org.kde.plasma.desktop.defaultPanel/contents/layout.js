var panel = new Panel
var panelScreen = panel.screen

// No need to set panel.location as ShellCorona::addPanel will automatically pick one available edge

// For an Icons-Only Task Manager on the bottom, *3 is too much, *2 is too little
// Round down to next highest even number since the Panel size widget only displays
// even numbers
panel.height = 2 * Math.floor(gridUnit * 2.5 / 2)

// Restrict horizontal panel to a maximum size of a 21:9 monitor
const maximumAspectRatio = 21/9;
if (panel.formFactor === "horizontal") {
    const geo = screenGeometry(panelScreen);
    const maximumWidth = Math.ceil(geo.height * maximumAspectRatio);

    if (geo.width > maximumWidth) {
        panel.alignment = "center";
        panel.minimumLength = maximumWidth;
        panel.maximumLength = maximumWidth;
    }
}

panel.addWidget("org.kde.plasma.kickoff")
//panel.addWidget("org.kde.plasma.showActivityManager")
panel.addWidget("org.kde.plasma.pager")
// nativeqt: Plasma's pinned launchers (the task manager's default: System Settings, Discover, the file manager, the
// browser) without those whose application is not installed. Debian's disk has no Discover: its launcher showed
// the generic icon, and a click on it was a notification, "Could not read file applications:org.kde.discover.desktop".
var tasks = panel.addWidget("org.kde.plasma.icontasks")
var launchers = []
for (const id of ["systemsettings", "org.kde.discover"]) {
    if (applicationPath(id)) {
        launchers.push("applications:" + id + ".desktop")
    }
}
launchers.push("preferred://filemanager", "preferred://browser")
// (an array: a string would be one launcher for the running applet, whose config scheme takes the value as a one-item list)
tasks.currentConfigGroup = ["General"]
tasks.writeConfig("launchers", launchers)
panel.addWidget("org.kde.plasma.marginsseparator")

