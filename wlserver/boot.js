// wlserver: the window server of the page, as a process of the machine.
//
// A Wayland compositor, written in JavaScript and run by the browser's own
// engine the way hostnode runs Node.js programs (hostnode/boot.js says how:
// /bin/hostnode reads $HOSTNODE_HOME/boot.js and hands it to the host with
// __run_js, and from then on this text is the program of the task, making
// the kernel's system calls itself). What makes a compositor want to be
// here rather than a riscv64 program under the emulator: it sees the whole
// memory of the machine, so the pixels its clients draw are, to it and to
// the page, the same bytes, and nothing is copied; and it is JavaScript,
// close to the page that draws the windows.
//
// The parts, all in the directory this file was read from:
//   boot.js        this: memory, system calls, files, loading the other parts
//   protocol.js    the protocol's tables (generated by tools/wayland-scanner.js)
//   wire.js        messages in and out of a client's socket
//   table.js       the surface table the page draws from (README.md: the layout)
//   compositor.js  what the messages mean: objects, surfaces, buffers, the table's side
//   shell.js       windows: xdg-shell, decorations, the page's orders (move, resize, close)
//   apps.js        the programs there are (.desktop files), for the page's launcher, and starting one
//   keyboard.js    the keyboard's layouts (keymaps/) and the modifiers' state for the one in use
//   seat.js        input: the keyboard and the pointer (from /dev/input), focus, the pointer's picture
//   data.js        the clipboard (and the primary selection), the bridge to the host's clipboard, host files
//   textinput.js   text from the host's input method (zwp_text_input_v3): Japanese, Chinese, Korean, ...
//   drag.js        drag and drop between windows, and host files dropped on a window
//   x11.js         the X11 protocol, the client's side (for xwm.js and xselection.js)
//   xwm.js         X programs: Xwayland started when one connects, and the X window manager
//   xselection.js  the clipboard between X programs and Wayland ones
//   server.js      the socket, the clients, the turns
//   plasma.js      Plasma's configuration and theme files for the page (read-only), told when they change
//   kconfig.js     KDE's configuration files, read and written as KConfig does
//   desktops.js    virtual desktops (kwinrc [Desktops]), the page's desktop orders
//   rules.js       window rules (kwinrulesrc)
//   dbus.js        D-Bus, the client's side, on the session bus
//   kwin.js        org.kde.KWin (desktops, reconfigure) and org.kde.plasmashell (the wallpaper) on the bus
//   notify.js      org.freedesktop.Notifications and org.kde.StatusNotifierWatcher, drawn by the page
//   ksplash.js     org.kde.KSplash: the session's programs' splash stages, for the page's splash screen
//
// Started by `desktop wayland PROGRAM` (tools/x/desktop) as
// HOSTNODE_HOME=/run/wlserver hostnode, with XDG_RUNTIME_DIR set.
// WLSERVER_DEBUG=1 logs every message; WLSERVER_STATS=1 a line of counts
// every five seconds; HOSTNODE_STRACE=1 every system call.
(function (host) {
  "use strict";

  const memory = host.memory;
  const C = host.instance.exports;	// the C library under us (hostnode.c exports everything)
  const K = host.syscalls;
  const SP = host.stack_pointer.value;
  const TP = C.__get_tls_base();

  const B = BigInt, N = Number;
  let sys0 = (n) => N(K[0](SP, TP, B(n)));
  let sys1 = (n, a) => N(K[1](SP, TP, B(n), B(a)));
  let sys2 = (n, a, b) => N(K[2](SP, TP, B(n), B(a), B(b)));
  let sys3 = (n, a, b, c) => N(K[3](SP, TP, B(n), B(a), B(b), B(c)));
  let sys4 = (n, a, b, c, d) => N(K[4](SP, TP, B(n), B(a), B(b), B(c), B(d)));
  let sys5 = (n, a, b, c, d, e) => N(K[5](SP, TP, B(n), B(a), B(b), B(c), B(d), B(e)));
  let sys6 = (n, a, b, c, d, e, f) => N(K[6](SP, TP, B(n), B(a), B(b), B(c), B(d), B(e), B(f)));

  // The kernel's numbers (include/uapi/asm-generic/unistd.h).
  const SYS = {
    epoll_create1: 20, epoll_ctl: 21, epoll_pwait: 22, fcntl: 25, flock: 32, ioctl: 29, mkdirat: 34, unlinkat: 35,
    ftruncate: 46, openat: 56, close: 57, pipe2: 59, read: 63, write: 64, pread64: 67, ppoll: 73,
    signalfd4: 74, fstat: 80, exit: 93, exit_group: 94, nanosleep: 101, clock_gettime: 113, kill: 129,
    rt_sigaction: 134, faccessat: 48, rt_sigprocmask: 135, getpid: 172, getdents64: 61, wait4: 260, socket: 198, bind: 200, listen: 201, accept: 202,
    connect: 203, socketpair: 199, sendmsg: 211, recvmsg: 212, munmap: 215, mmap: 222, mremap: 216, accept4: 242,
    getsockopt: 209, readlinkat: 78,
  };

  let buffer = memory.buffer;
  let bytes = new Uint8Array(buffer);
  let view = new DataView(buffer);
  const renew = () => {
    buffer = memory.buffer;
    bytes = new Uint8Array(buffer);
    view = new DataView(buffer);
  };
  const u8 = () => {
    if (memory.buffer !== buffer) {
      renew();
    }
    return bytes;
  };
  const dv = () => {
    if (memory.buffer !== buffer) {
      renew();
    }
    return view;
  };

  const alloc = (size) => {
    const address = N(C.malloc(B(size)));
    if (!address) {
      throw new RangeError("wlserver: out of memory (" + size + " bytes)");
    }
    return address;
  };
  const free = (address) => C.free(B(address));

  const decoder = new TextDecoder("utf-8");
  const encoder = new TextEncoder();
  const text = (address, length) => decoder.decode(u8().slice(address, address + length));
  const cstring = (address) => {
    const m = u8();
    let end = address;
    while (m[end]) {
      end++;
    }
    return text(address, end - address);
  };

  const PATH_MAX = 4096;
  const SCRATCH = 65536;
  const P0 = alloc(2 * PATH_MAX + SCRATCH);
  const P1 = P0 + PATH_MAX;
  const S = P1 + PATH_MAX;

  class SystemError extends Error {
    constructor(errno, what) {
      super(what + ": error " + errno);
      this.errno = errno;
    }
  }

  const path = (p, where) => {
    const raw = encoder.encode(p);
    if (raw.length >= PATH_MAX) {
      return -36;
    }
    const m = u8();
    m.set(raw, where);
    m[where + raw.length] = 0;
    return where;
  };

  const O_RDONLY = 0, O_CLOEXEC = 0o2000000;
  const AT_FDCWD = -100;
  const EINTR = 4, EAGAIN = 11;

  const readFile = (name) => {
    const fd = sys4(SYS.openat, AT_FDCWD, path(name, P0), O_RDONLY | O_CLOEXEC, 0);
    if (fd < 0) {
      return null;
    }
    const chunks = [];
    let total = 0;
    for (;;) {
      const n = sys3(SYS.read, fd, S, SCRATCH);
      if (n === -EINTR) {
        continue;
      }
      if (n <= 0) {
        break;
      }
      chunks.push(u8().slice(S, S + n));
      total += n;
    }
    sys1(SYS.close, fd);
    const all = new Uint8Array(total);
    let at = 0;
    for (const chunk of chunks) {
      all.set(chunk, at);
      at += chunk.length;
    }
    return all;
  };
  const readText = (name) => {
    const data = readFile(name);
    return data === null ? null : decoder.decode(data);
  };

  const writeAll = (fd, data) => {
    if (typeof data === "string") {
      data = encoder.encode(data);
    }
    let done = 0;
    while (done < data.length) {
      const part = Math.min(data.length - done, SCRATCH);
      u8().set(data.subarray(done, done + part), S);
      const n = sys3(SYS.write, fd, S, part);
      if (n === -EINTR) {
        continue;
      }
      if (n === -EAGAIN) {
        const v = dv();
        v.setInt32(S, fd, true);
        v.setInt16(S + 4, 4, true);
        v.setInt16(S + 6, 0, true);
        sys5(SYS.ppoll, S, 1, 0, 0, 0);
        continue;
      }
      if (n < 0) {
        return n;
      }
      done += n;
    }
    return done;
  };

  const exit = (code) => {
    sys1(SYS.exit_group, code & 0xff);
    for (;;) {
      sys1(SYS.exit, code & 0xff);
    }
  };

  // What the Wasm program told us (struct hn_start in hostnode.c).
  const start = N(host.arg);
  const pointers = (address) => {
    const list = [];
    for (let at = address; ; at += 8) {
      const p = N(dv().getBigUint64(at, true));
      if (!p) {
        return list;
      }
      list.push(cstring(p));
    }
  };
  const argv = pointers(N(dv().getBigUint64(start + 8, true)));
  const envp = pointers(N(dv().getBigUint64(start + 16, true)));
  const home = cstring(N(dv().getBigUint64(start + 24, true)));

  // Every line of the log on standard error (the desktop script sends it to /root/wlserver.log).
  const log = (line) => {
    writeAll(2, line + "\n");
  };

  // HOSTNODE_STRACE=1: every system call, said before it is made and again with its result.
  if (envp.includes("HOSTNODE_STRACE=1")) {
    const names = {};
    for (const name of Object.keys(SYS)) {
      names[SYS[name]] = name;
    }
    let depth = 0;
    const wrap = (count) => (n, ...args) => {
      if (depth > 0 || (n === SYS.write && args[0] === 2)) {
        return N(K[count](SP, TP, B(n), ...args.map(B)));
      }
      depth++;
      let r;
      try {
        r = N(K[count](SP, TP, B(n), ...args.map(B)));
      } finally {
        depth--;
      }
      if (n !== SYS.epoll_pwait || r !== 0) {
        log("[strace] " + (names[n] || n) + "(" + args.join(", ") + ") = " + r);
      }
      return r;
    };
    sys0 = wrap(0);
    sys1 = wrap(1);
    sys2 = wrap(2);
    sys3 = wrap(3);
    sys4 = wrap(4);
    sys5 = wrap(5);
    sys6 = wrap(6);
  }

  // A client that went away while we write to it is not the end of us.
  C.hn_signal(13, 1);

  const ws = {
    host, memory, C, SYS, sys0, sys1, sys2, sys3, sys4, sys5, sys6,
    u8, dv, alloc, free, text, cstring, path, P0, P1, S, SCRATCH, PATH_MAX,
    readFile, readText, writeAll, exit, SystemError, argv, envp, home, log,
    debug: envp.includes("WLSERVER_DEBUG=1"),
    screen: { width: 1024, height: 768, scale: 1, panel: 0 },	// (until the page says: table.js, output; panel: the strip at the bottom it keeps)
    // The frame the page draws around a decorated window: a title bar above it and a border (tools/www/chrome.css).
    chrome: { title: 28, border: 4 },
    stats: { clients: 0, presents: 0, damageBytes: 0, pools: 0, resizes: 0 },
  };

  // The page load this machine belongs to: rvtab=ID on the kernel's command line (tools/www/dev.html), which names
  // the BroadcastChannel to the page, "rv-display-ID" (tools/www/display.js: window.rvChannel). A BroadcastChannel
  // reaches every tab of the origin, so a server and a page that did not share an id would hear other tabs'. With
  // no id (a machine run without a page: tools/node-machine.js) the channel's name is as it was, "rv-display".
  {
    const found = /(?:^|\s)rvtab=([0-9A-Za-z-]+)/.exec(readText("/proc/cmdline") || "");
    ws.tab = found ? found[1] : "";
    ws.channel = (name) => new BroadcastChannel(ws.tab ? name + "-" + ws.tab : name);
  }

  ws.fatal = (error) => {
    let message;
    try {
      message = error && error.stack ? String(error.stack) : String(error);
    } catch (e) {
      message = "(an error that cannot be shown)";
    }
    log("wlserver: " + message);
    exit(70);
  };

  // Another part of this program: a file here, whose text is an expression for a function of ws (or, for
  // protocol.js, of nothing, returning the tables).
  ws.load = (name) => {
    const source = readText(home + "/" + name);
    if (source === null) {
      throw new Error("wlserver: cannot read " + home + "/" + name);
    }
    return (0, eval)(source + "\n//# sourceURL=wlserver:" + name)(ws);
  };

  // The page's splash screen (tools/www/splash.js, drawn as Plasma's KSplash draws it) is told the stages of our
  // start, by KSplash's names, as they happen: "initial" now, before anything else is loaded, so that the page
  // covers the screen at once and never shows a desktop that is not ready; the table's announcement is "wm";
  // "ksmserver" when the session's services are on the bus. (ksplash.js takes org.kde.KSplash setStage from the
  // session's programs, and sends what they say the same way.)
  {
    const pid = sys0(SYS.getpid);
    let splash = null;
    try {
      splash = ws.channel("rv-display");
    } catch (error) {
      splash = null;
    }
    ws.splashStage = (stage) => {
      if (splash) {
        splash.postMessage({ type: "splash", pid, stage });
      }
    };
    ws.splashStage("initial");
  }

  try {
    ws.protocol = ws.load("protocol.js");
    ws.load("wire.js");
    ws.load("table.js");
    ws.load("compositor.js");
    ws.load("dmabuf.js");
    ws.load("shell.js");
    ws.load("kconfig.js");
    ws.load("desktops.js");
    ws.load("rules.js");
    ws.load("apps.js");
    ws.load("keyboard.js");
    ws.table.layoutDone(0, 0, ws.kbd.keymap ? ws.kbd.keymap.name : "");
    ws.load("seat.js");
    ws.load("layershell.js");
    ws.load("plasmashell.js");
    ws.load("data.js");
    ws.load("textinput.js");
    ws.load("drag.js");
    ws.load("x11.js");
    ws.load("xwm.js");
    ws.load("xselection.js");
    ws.load("server.js");
    // (After the server's loop: it watches the configuration with ws.watchFd. ?chrome=plain on the page ignores it.)
    try {
      ws.load("plasma.js");
    } catch (error) {
      log("plasma: " + (error && error.stack || error) + " (the page's frames stay plain)");
    }
    // KDE's services on the session bus: KWin's and plasmashell's (desktops, rules, the wallpaper), notifications.
    try {
      ws.load("dbus.js");
      ws.load("kwin.js");
      ws.load("notify.js");
      ws.load("ksplash.js");
    } catch (error) {
      log("dbus: " + (error && error.stack || error) + " (no KDE services on the bus)");
    }
    ws.splashStage("ksmserver");	// (the session's services are up, or will not be: either way the splash goes on)
  } catch (error) {
    if (error && error.name === "Trap") {
      throw error;
    }
    ws.fatal(error);
  }
})
